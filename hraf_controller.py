async def vlm_worker(bridge: StateBridge, harm: HARM, profiler: PerformanceProfiler, stop_event: asyncio.Event):
    """VLM loop producing asynchronous commands every 500ms (2 Hz)."""
    while not stop_event.is_set():
        t_start = asyncio.get_running_loop().time()
        try:
            raw_vlm_command = await async_run_sat("cam_0.png", "dummy_key")
            if raw_vlm_command:
                raw_text = raw_vlm_command.raw_response
                current_state = bridge.get_latest_state()

                # Measure HARM latency
                t0 = time.perf_counter()
                val_cmd, _ = harm.validate(raw_text, current_state)
                latency = (time.perf_counter() - t0) * 1000.0

                profiler.record_harm(latency)
                await bridge.put_command(val_cmd)
        except Exception as e:
            print(f"⚠️ VLM Worker Error: {e}")

        await asyncio.sleep(0.5)


async def ik_worker_100hz(bridge: StateBridge, profiler: PerformanceProfiler, stop_event: asyncio.Event):
    """High-frequency 100 Hz motor loop tracking timing stability."""
    target_interval = 0.010  # 10ms per cycle (100 Hz)
    joint1, joint2 = 0.0, 0.0
    last_tick_time = time.perf_counter()

    while not stop_event.is_set():
        t_start = time.perf_counter()

        # Record interval between ticks
        tick_interval_ms = (t_start - last_tick_time) * 1000.0
        last_tick_time = t_start
        profiler.record_ik_tick(tick_interval_ms)

        # Update telemetry feed
        bridge.update_telemetry(positions=[joint1, joint2], timestamp=t_start)

        # Process active command
        if bridge.has_command():
            current_cmd = await bridge.get_latest_command()
            if current_cmd and current_cmd.waypoints:
                target_wp = current_cmd.waypoints[0]
                joint1 += (target_wp[0] - joint1) * 0.1
                joint2 += (target_wp[-1] - joint2) * 0.1

        # Precise 100 Hz pacing
        elapsed = time.perf_counter() - t_start
        sleep_dur = target_interval - elapsed
        if sleep_dur > 0:
            await asyncio.sleep(sleep_dur)
        else:
            await asyncio.sleep(0.001)


