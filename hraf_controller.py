async def monitored_vlm_loop(
    bridge: StateBridge,
    harm_engine: HARM,
    profiler: HARMProfiler,
    image_source: str,
    api_key: str,
    target_hz: float = 2.0,
    max_cycles: int = 5
):
    """
    VLM loop with HARM diagnostic counter tracking and microsecond-level timing profiler.
    """
    print(f"👁️ [HRAF CONTROLLER] Stage 2 Monitored VLM Loop Active ({target_hz} Hz)")
    time_per_cycle = 1.0 / target_hz
    cycle_count = 0

    while cycle_count < max_cycles:
        start_time = asyncio.get_running_loop().time()
        cycle_count += 1

        try:
            # Step A: Fetch raw VLM output
            raw_vlm_command = await async_run_sat(image_source, api_key)
            if raw_vlm_command is None:
                continue

            raw_text = raw_vlm_command.raw_response
            current_state = bridge.get_latest_state()

            # Step B: Profile HARM Validation Latency
            t0 = time.perf_counter()
            validated_command, harm_receipt = harm_engine.validate(raw_text, current_state)
            latency_ms = (time.perf_counter() - t0) * 1000.0

            # Step C: Record Diagnostics
            profiler.record_validation(harm_receipt.status, latency_ms)

            print(f"\n--- [VLM Cycle {cycle_count}] ---")
            print(f"Status: {harm_receipt.status} | Latency: {latency_ms:.3f} ms")
            if harm_receipt.validation_notes:
                print(f"Notes: {harm_receipt.validation_notes}")

            # Step D: Route to bridge
            await bridge.put_command(validated_command)

        except Exception as err:
            print(f"⚠️ [VLM LOOP] Exception: {err}")

        # Maintain loop frequency timing
        elapsed = asyncio.get_running_loop().time() - start_time
        remaining = time_per_cycle - elapsed
        if remaining > 0:
            await asyncio.sleep(remaining)


