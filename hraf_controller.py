# 1. LATENCY PROFILER & DIAGNOSTIC TRACKER
# ==========================================
class HARMProfiler:
    """
    Tracks safety diagnostics and monitors processing latency against the 5ms timing budget.
    """
    def __init__(self):
        self.intercepted_count = 0
        self.recovered_count = 0
        self.fallback_count = 0
        self.passed_count = 0
        self.latencies_ms: List[float] = []

    def record_validation(self, status: str, latency_ms: float):
        self.intercepted_count += 1
        self.latencies_ms.append(latency_ms)

        if status == "PASSED":
            self.passed_count += 1
        elif status == "RECOVERED":
            self.recovered_count += 1
        elif status == "FALLBACK":
            self.fallback_count += 1

    def get_summary(self) -> Dict[str, float]:
        avg_latency = sum(self.latencies_ms) / len(self.latencies_ms) if self.latencies_ms else 0.0
        max_latency = max(self.latencies_ms) if self.latencies_ms else 0.0
        return {
            "intercepted": self.intercepted_count,
            "passed": self.passed_count,
            "recovered": self.recovered_count,
            "fallback": self.fallback_count,
            "avg_latency_ms": round(avg_latency, 3),
            "max_latency_ms": round(max_latency, 3),
            "budget_met (<5ms)": max_latency < 5.0
        }


