# Calculate smooth moving average frequencies for plotting
def compute_moving_hz(timestamps, window_size=50):
    if len(timestamps) < window_size:
        return [], []
    norm_times = np.array(timestamps) - timestamps[0]
    hz_list, time_list = [], []
