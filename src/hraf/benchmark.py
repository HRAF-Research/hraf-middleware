# Mock re-prompt function for Stage 1 schema recovery
def mock_vlm_reprompt(bad_raw: str, error_msg: str) -> str:
    if "CRITICAL_SYSTEM_MALFUNCTION" in bad_raw:
        return ""
    return '{"action": "MOVE", "waypoints": [[0.5, 0.5]], "confidence": 0.95}'

def generate_synthetic_vlm_payload() -> str:
    """Generates dynamic VLM responses (nominal, schema bugs, boundary clips, kinematic spikes)."""
    rand = random.random()
    if rand < 0.60:
        return json.dumps({"action": "MOVE", "waypoints": [[0.4, -0.2]], "confidence": 0.95})
    elif rand < 0.75:
        return '{"action": "MOVE", "waypoints": [[0.4, 0.0]] "confidence": 0.95}'
    elif rand < 0.88:
        return json.dumps({"action": "MOVE", "waypoints": [[4.5, -2.0]], "confidence": 0.90})
    elif rand < 0.96:
        return json.dumps({"action": "MOVE", "waypoints": [[1.2, 0.0]], "confidence": 0.92})
    else:
        return "CRITICAL_SYSTEM_MALFUNCTION_EMPTY_STRING"


class BenchmarkHarness:
    """Executes 60-second comparative evaluation across Single vs Dual-Frequency architectures."""
    def __init__(self, duration_sec: float = 60.0):
        self.duration_sec = duration_sec
        self.harm_engine = HARM(mock_vlm_reprompt_fn=mock_vlm_reprompt)

    # =========================================================================
    # SYSTEM A: SYNCHRONOUS SINGLE-FREQUENCY BASELINE (Sequential VLM -> IK)
    # =========================================================================
    def run_single_frequency_baseline(self) -> Dict[str, Any]:
        print(f"\n🐢 [SYSTEM A] Running Single-Frequency Synchronous Baseline ({self.duration_sec}s)...")

        robot_state = RobotState(positions=[0.0, 0.0], timestamp=time.time())
        ik_timestamps: List[float] = []
        vlm_timestamps: List[float] = []
        harm_results: List[Dict[str, Any]] = []
        staleness_logs: List[float] = []

        start_time = time.time()

        while (time.time() - start_time) < self.duration_sec:
            cycle_start = time.time()

            vlm_timestamps.append(cycle_start)
            raw_vlm = generate_synthetic_vlm_payload()
            time.sleep(0.300)

            validated_cmd, receipt = self.harm_engine.validate(raw_vlm, robot_state)
            harm_results.append(receipt.model_dump())

            ik_start = time.time()
            ik_timestamps.append(ik_start)
            time.sleep(0.005)

            staleness = time.time() - cycle_start
            staleness_logs.append(staleness)

            if validated_cmd.waypoints:
                robot_state.positions = validated_cmd.waypoints[0]

        total_elapsed = time.time() - start_time
        effective_ik_hz = len(ik_timestamps) / total_elapsed

        return {
            "system_name": "Single-Frequency Baseline",
            "duration_sec": round(total_elapsed, 2),
            "total_vlm_calls": len(vlm_timestamps),
            "total_ik_ticks": len(ik_timestamps),
            "effective_ik_hz": round(effective_ik_hz, 2),
            "avg_staleness_sec": round(sum(staleness_logs) / len(staleness_logs), 3) if staleness_logs else 0.0,
            "harm_results": harm_results,
            "ik_timestamps": ik_timestamps,
            "vlm_timestamps": vlm_timestamps,
            "staleness_logs": staleness_logs
        }

    # =========================================================================
    # SYSTEM B: ASYNCHRONOUS DUAL-FREQUENCY ENGINE (2 Hz VLM || 100 Hz IK)
    # =========================================================================
    async def run_dual_frequency_async_engine(self) -> Dict[str, Any]:
        print(f"\n⚡ [SYSTEM B] Running Dual-Frequency Asynchronous Engine ({self.duration_sec}s)...")

        robot_state = RobotState(positions=[0.0, 0.0], timestamp=time.time())
        ik_timestamps: List[float] = []
        vlm_timestamps: List[float] = []
        harm_results: List[Dict[str, Any]] = []
        staleness_logs: List[float] = []

        latest_command: VLMCommand = VLMCommand(
            action="HOLD",
            waypoints=[robot_state.positions],
            confidence=0.0
        )
        last_vlm_update_time: float = time.time()
        stop_event = asyncio.Event()

        async def vlm_worker():
            nonlocal latest_command, last_vlm_update_time
            while not stop_event.is_set():
                vlm_start = asyncio.get_running_loop().time()
                vlm_timestamps.append(vlm_start)

                await asyncio.sleep(0.300)
                raw_vlm = generate_synthetic_vlm_payload()

                val_cmd, receipt = self.harm_engine.validate(raw_vlm, robot_state)
                harm_results.append(receipt.model_dump())

                latest_command = val_cmd
                last_vlm_update_time = time.time()

                elapsed = asyncio.get_running_loop().time() - vlm_start
                remaining = 0.500 - elapsed
                if remaining > 0:
                    await asyncio.sleep(remaining)

        async def ik_worker():
            nonlocal robot_state
            target_interval = 0.010  # 10ms (100 Hz)

            while not stop_event.is_set():
                t_start = asyncio.get_running_loop().time()
                ik_timestamps.append(t_start)

                staleness = time.time() - last_vlm_update_time
                staleness_logs.append(staleness)

                await asyncio.sleep(0.005)

                if latest_command.waypoints:
                    target_wp = latest_command.waypoints[0]
                    robot_state.positions[0] += (target_wp[0] - robot_state.positions[0]) * 0.1
                    robot_state.positions[1] += (target_wp[1] - robot_state.positions[1]) * 0.1

                elapsed = asyncio.get_running_loop().time() - t_start
                remaining = target_interval - elapsed
                if remaining > 0:
                    await asyncio.sleep(remaining)

        vlm_task = asyncio.create_task(vlm_worker())
        ik_task = asyncio.create_task(ik_worker())

        start_wall_time = time.time()
        await asyncio.sleep(self.duration_sec)

        stop_event.set()
        await asyncio.gather(vlm_task, ik_task)

        total_elapsed = time.time() - start_wall_time
        effective_ik_hz = len(ik_timestamps) / total_elapsed

        return {
            "system_name": "Dual-Frequency Async Engine",
            "duration_sec": round(total_elapsed, 2),
            "total_vlm_calls": len(vlm_timestamps),
            "total_ik_ticks": len(ik_timestamps),
            "effective_ik_hz": round(effective_ik_hz, 2),
            "avg_staleness_sec": round(sum(staleness_logs) / len(staleness_logs), 3) if staleness_logs else 0.0,
            "harm_results": harm_results,
            "ik_timestamps": ik_timestamps,
            "vlm_timestamps": vlm_timestamps,
            "staleness_logs": staleness_logs
        }


async def main():
    harness = BenchmarkHarness(duration_sec=60.0)

    baseline_res = harness.run_single_frequency_baseline()
    async_res = await harness.run_dual_frequency_async_engine()

    print("\n" + "="*65)
    print("📊 60-SECOND BENCHMARK HARNESS COMPARISON RESULTS")
    print("="*65)
    print(f"{'Metric':<30} | {'Single-Freq Baseline':<20} | {'Dual-Freq Async':<20}")
    print("-" * 75)
    print(f"{'Effective IK Frequency (Hz)':<30} | {baseline_res['effective_ik_hz']:<20} | {async_res['effective_ik_hz']:<20}")
    print(f"{'Total IK Ticks':<30} | {baseline_res['total_ik_ticks']:<20} | {async_res['total_ik_ticks']:<20}")
    print(f"{'Total VLM Calls':<30} | {baseline_res['total_vlm_calls']:<20} | {async_res['total_vlm_calls']:<20}")
    print(f"{'Avg Command Staleness (s)':<30} | {baseline_res['avg_staleness_sec']:<20} | {async_res['avg_staleness_sec']:<20}")
    print("="*65)

    # 1. Export High-Level Summary CSV
    summary_cols = ["system_name", "duration_sec", "total_vlm_calls", "total_ik_ticks", "effective_ik_hz", "avg_staleness_sec"]
    df_summary = pd.DataFrame([
        {k: baseline_res[k] for k in summary_cols},
        {k: async_res[k] for k in summary_cols}
    ])
    summary_filename = "benchmark_60s_summary.csv"
    df_summary.to_csv(summary_filename, index=False)

    # 2. Export Detailed Timestamp Logs CSV
    timestamp_rows = []
    for sys_res in [baseline_res, async_res]:
        name = sys_res["system_name"]
        for idx, (t_ik, staleness) in enumerate(zip(sys_res["ik_timestamps"], sys_res["staleness_logs"])):
            harm_entry = sys_res["harm_results"][idx % len(sys_res["harm_results"])] if sys_res["harm_results"] else {}
            timestamp_rows.append({
                "system_name": name,
                "ik_tick_id": idx + 1,
                "ik_timestamp": t_ik,
                "command_staleness_sec": round(staleness, 4),
                "harm_catch_type": harm_entry.get("catch_type", "none"),
                "harm_stage_failed": harm_entry.get("stage_failed", "NONE"),
                "harm_error_type": harm_entry.get("error_type", "NONE")
            })

    df_timestamps = pd.DataFrame(timestamp_rows)
    timestamps_filename = "benchmark_60s_timestamps.csv"
    df_timestamps.to_csv(timestamps_filename, index=False)

    print(f"\n✅ Files created successfully: {summary_filename}, {timestamps_filename}")

    # Trigger Google Colab downloads directly
    files.download(summary_filename)
    files.download(timestamps_filename)

await main()