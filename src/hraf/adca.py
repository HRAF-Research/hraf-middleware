async def safe_vlm_loop(
    bridge: StateBridge,
    image_source: str,
    api_key: str,
    harm_engine: Optional[Any] = None,
    profiler: Optional[Any] = None,
    target_hz: float = 2.0
):
    """
    Continuous vision worker loop integrated with HARM validation and telemetry profiling.
    Catches pipeline failures cleanly without crashing.
    """
    print(f"👁️ VLM Loop Active (HARM-Integrated). Operating target speed: {target_hz} Hz")
    time_per_cycle = 1.0 / target_hz

    while True:
        start_time = asyncio.get_running_loop().time()
        try:
            raw_vlm_command = await async_run_sat(image_source, api_key)
            if raw_vlm_command is None:
                print("⚠️ [ERROR LOG] Blank 'None' data received! Skipping cycle update.")
                await _maintain_loop_timing(start_time, time_per_cycle)
                continue

            # --- HARM INTEGRATION STEP ---
            if harm_engine is not None:
                t0 = time.perf_counter()
                current_state = {"positions": [0.0, 0.0, 0.0], "timestamp": time.time()}

                # Intercept and validate raw VLM payload
                validated_cmd, receipt = harm_engine.validate(raw_vlm_command.raw_response, current_state)
                latency_ms = (time.perf_counter() - t0) * 1000.0

                if profiler is not None:
                    profiler.record_validation(getattr(receipt, 'status', 'PASSED'), latency_ms)

                final_command = validated_cmd
            else:
                final_command = raw_vlm_command

            # Deposit validated command into non-blocking StateBridge
            await bridge.put_command(final_command)

        except asyncio.TimeoutError:
            print("⚠️ [ERROR LOG] Vision server timeout encountered! Skipping cycle update.")
            await _maintain_loop_timing(start_time, time_per_cycle)
            continue
        except Exception as err:
            print(f"⚠️ [ERROR LOG] API Error encountered: Network disconnect ({err}). Skipping cycle update.")
            await _maintain_loop_timing(start_time, time_per_cycle)
            continue

        await _maintain_loop_timing(start_time, time_per_cycle)

