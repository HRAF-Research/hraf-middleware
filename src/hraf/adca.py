@dataclass
class VLMCommand:
    """The unified command data model passed between vision and hardware loops."""
    waypoints: List[List[float]]  # Target path positions in meters (m) along [X, Y, Z] axes
    obstacles: List[str]          # Plain text labels identifying nearby barriers
    confidence: float             # AI model accuracy probability scale ranging from 0.0 to 1.0
    raw_response: str             # Unparsed raw text output directly from the cloud model
    action: str = "MOVE"          # Control mode keyword directive for the robot arm joints
    sat_class: str = "UNKNOWN"    # SAT classification from real perception pipeline

@dataclass
class RobotState:
    """Telemetry state passed into HARM for safety verification."""
    positions: List[float] = field(default_factory=lambda: [0.0, 0.0, 0.0])
    velocity: List[float] = field(default_factory=lambda: [0.0, 0.0, 0.0])
    timestamp: float = field(default_factory=time.time)

@dataclass
class HARMReceipt:
    """Validation receipt generated by the HARM safety engine."""
    status: str                   # "PASSED", "INTERCEPTED", "FALLBACK"
    catch_type: Optional[str] = None
    stage_failed: Optional[int] = None
    error_type: Optional[str] = None
    latency_ms: float = 0.0

# ==========================================
# 2. REAL VLM PIPELINE ADAPTER
# ==========================================
def real_sat_adapter(image_path: str, api_key: str) -> VLMCommand:
    """
    Synchronous wrapper adapter for Intern 2's run_sat().
    Converts returned dictionary to unified VLMCommand object.
    """
    sat_result = run_sat(image_path, api_key)

    # Calculate confidence based on pipeline validation pass
    conf = 0.95 if sat_result.get("validation_passed") else (0.50 if sat_result.get("parse_success") else 0.0)

    # Convert object/sat_class metadata into obstacles tracking
    obj_name = sat_result.get("object_name", "UNKNOWN")
    sat_cls = sat_result.get("sat_class", "UNKNOWN")
    obstacle_label = f"{obj_name}:{sat_cls}"

    return VLMCommand(
        waypoints=[[0.25, -0.10, 0.45], [0.30, 0.00, 0.50]], # Default trajectory
        obstacles=[obstacle_label],
        confidence=conf,
        raw_response=sat_result.get("raw_response", ""),
        action="MOVE" if sat_result.get("validation_passed") else "HOLD",
        sat_class=sat_cls
    )

