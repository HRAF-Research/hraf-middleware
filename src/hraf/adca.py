# 3. NON-BLOCKING THREAD WRAPPER BRIDGE
# ==========================================
async def async_run_sat(image_path: str, api_key: str, timeout_seconds: float = 3.0) -> VLMCommand:
    """
    Wraps the synchronous VLM pipeline call inside a background thread worker
    and enforces a maximum safety timeout countdown window.
    """
    loop = asyncio.get_running_loop()
    try:
        # Offloads synchronous blocking Groq/HTTP pipeline to a thread executor safely
        vlm_command = await asyncio.wait_for(
            loop.run_in_executor(None, real_sat_adapter, image_path, api_key),
            timeout=timeout_seconds
        )
        return vlm_command
    except asyncio.TimeoutError:
        print(f"⚠️ [TIMEOUT] Real VLM Pipeline exceeded safety limit of {timeout_seconds}s!")
        raise

